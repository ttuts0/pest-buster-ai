-- PestBusterAI database schema (PostgreSQL 13+)
-- Follows section 2A of the System Architecture & Data Design document.
-- Chain: vineyards -> blocks -> flights -> images -> detections

CREATE TABLE users (
    user_id        BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email          TEXT NOT NULL UNIQUE,
    password_hash  TEXT NOT NULL,
    full_name      TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE vineyards (
    vineyard_id    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    address        TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- junction: users N:M vineyards
CREATE TABLE vineyard_members (
    vineyard_id    BIGINT NOT NULL REFERENCES vineyards ON DELETE CASCADE,
    user_id        BIGINT NOT NULL REFERENCES users     ON DELETE CASCADE,
    role           TEXT NOT NULL CHECK (role IN ('owner', 'operator', 'viewer')),
    joined_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (vineyard_id, user_id)
);

CREATE TABLE blocks (
    block_id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    vineyard_id       BIGINT NOT NULL REFERENCES vineyards ON DELETE CASCADE,
    name              TEXT NOT NULL,
    grape_variety     TEXT,
    boundary_geojson  JSONB,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (vineyard_id, name)
);

CREATE TABLE flights (
    flight_id         UUID PRIMARY KEY,      -- generated by the PBAI Android app
    block_id          BIGINT NOT NULL REFERENCES blocks ON DELETE CASCADE,
    operator_user_id  BIGINT REFERENCES users ON DELETE SET NULL,
    drone_serial      TEXT,
    started_at        TIMESTAMPTZ NOT NULL,
    ended_at          TIMESTAMPTZ,
    status            TEXT NOT NULL DEFAULT 'uploaded'
                      CHECK (status IN ('uploaded', 'processing', 'complete', 'failed')),
    image_count       INTEGER CHECK (image_count >= 0),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at      TIMESTAMPTZ
);

CREATE TABLE images (
    image_id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    flight_id          UUID NOT NULL REFERENCES flights ON DELETE CASCADE,
    s3_key             TEXT NOT NULL UNIQUE,
    sha256             CHAR(64) NOT NULL UNIQUE,   -- hex digest of the file
    original_filename  TEXT,
    captured_at        TIMESTAMPTZ NOT NULL,
    latitude           DOUBLE PRECISION NOT NULL CHECK (latitude  BETWEEN -90  AND 90),
    longitude          DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    altitude_m         REAL,
    analysis_status    TEXT NOT NULL DEFAULT 'queued'
                       CHECK (analysis_status IN ('queued', 'done', 'error')),
    uploaded_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    analyzed_at        TIMESTAMPTZ
);

CREATE TABLE disease_types (
    disease_type_id  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name             TEXT NOT NULL UNIQUE,
    description      TEXT
);

CREATE TABLE detections (
    detection_id     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    image_id         BIGINT NOT NULL REFERENCES images        ON DELETE CASCADE,
    disease_type_id  BIGINT NOT NULL REFERENCES disease_types ON DELETE RESTRICT,
    severity         TEXT CHECK (severity IN ('low', 'medium', 'high')),
    confidence       REAL CHECK (confidence BETWEEN 0 AND 1),
    bbox_x           REAL,
    bbox_y           REAL,
    bbox_w           REAL,
    bbox_h           REAL,
    model_version    TEXT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (image_id, disease_type_id, model_version, bbox_x, bbox_y)
);

-- Indexes on the foreign-key chain, so a lookup by flight touches only that flight's rows
CREATE INDEX vineyard_members_user_idx ON vineyard_members (user_id);
CREATE INDEX flights_block_idx         ON flights (block_id);
CREATE INDEX images_flight_idx         ON images (flight_id);
CREATE INDEX images_status_idx         ON images (analysis_status);
CREATE INDEX detections_image_idx      ON detections (image_id);
